"""Credit spoken-corpus counts to vocab.tsv entries.

Usage: python mapforms.py VOCAB MILLER STEMS SUBTITLES COLLOQ OUTDIR

MILLER is miller_ranks.tsv: the source list's ranks, which stay the base of the
reranking however often it is rerun.

Reads vocab.tsv, a present-stem table, the OpenSubtitles 2018 frequency list
(FrequencyWords fa_50k.txt) and a hand-made colloquial map, and writes:
  entry_counts.tsv  id, rank, word, pos, subtitle count, wordfreq frequency
  unmatched.tsv     subtitle forms credited to no entry, by count
A form generated by several entries is split between them in proportion to
1/rank in the existing list (the Miller ranks act as a prior).
"""
import csv, re, sys, collections, math
from wordfreq import word_frequency, top_n_list

VOCAB, MILLER, STEMS, SUBS, COLLOQ, OUT = sys.argv[1:7]

def norm(s):
    s = s.replace('ي', 'ی').replace('ك', 'ک').replace('ة', 'ه').replace('ى', 'ی').replace('أ', 'ا').replace('إ', 'ا').replace('ؤ', 'و')
    s = re.sub('[‌‍ـً-ْٰ]', '', s)
    return s.strip()

PREVERBS = ['باز', 'فرا', 'بر', 'در', 'وا', 'فرو']
NOMINAL = {'NOUN', 'ADJ', 'PROPN'}

miller = {r['id']: r['rank_miller'] for r in csv.DictReader(open(MILLER, encoding='utf-8'), delimiter='\t', quoting=csv.QUOTE_NONE)}
entries = []
for row in csv.DictReader(open(VOCAB, encoding='utf-8'), delimiter='\t', quoting=csv.QUOTE_NONE):
    if row['id'] not in miller:
        continue            # rows added by this tool are counted through COLLOQ
    row['rank'] = miller[row['id']]
    entries.append(row)

stems = {}
for line in open(STEMS, encoding='utf-8'):
    if line.startswith('#') or not line.strip():
        continue
    inf, st = line.rstrip('\n').split('\t')
    stems[inf] = [s.strip() for s in st.split(',') if s.strip()]

def present_stems(inf):
    if inf in stems:
        return stems[inf]
    if inf.endswith('یدن'):
        return [inf[:-3]]
    if inf.endswith('اندن'):
        return [inf[:-2]]
    return []

def nominal_forms(w, pos):
    fs = {w}
    if len(w) <= 1:
        return fs
    last = w[-1]
    vowel_end = last in 'او'
    h_end = last == 'ه'
    plural = [w + 'ان', w + 'ات', w + 'انی', w + 'های', w + 'ها', w + 'های', w + 'هایی', w + 'هام', w + 'هات', w + 'هاش',
              w + 'هامون', w + 'هاتون', w + 'هاشون', w + 'هایم', w + 'هایت', w + 'هایش',
              w + 'هایمان', w + 'هایتان', w + 'هایشان', w + 'هارو', w + 'هاشو']
    fs.update(plural)
    if h_end:
        fs.update([w + 'ای', w + 'ی', w + 'ام', w + 'ات', w + 'اش', w + 'مان', w + 'تان', w + 'شان',
                   w + 'مون', w + 'تون', w + 'شون', w + 'رو', w + 'ات'])
    elif vowel_end:
        fs.update([w + 'ش', w + 'ت', w + 'م', w + 'شون', w + 'تون', w + 'مون'])
        fs.update([w + 'یی', w + 'ی', w + 'یم', w + 'یت', w + 'یش', w + 'یمان', w + 'یتان',
                   w + 'یشان', w + 'یمون', w + 'یتون', w + 'یشون', w + 'رو'])
    else:
        fs.update([w + 'ی', w + 'م', w + 'ت', w + 'ش', w + 'مان', w + 'تان', w + 'شان',
                   w + 'مون', w + 'تون', w + 'شون', w + 'و', w + 'یم', w + 'یش'])
    if pos == 'ADJ':
        fs.update([w + 'تر', w + 'ترین', w + 'تری', w + 'ترش'])
    # colloquial plural in -ا and the clitic copula (خوبه، درسته، عالیه، کجاست)
    if not h_end and not vowel_end and len(w) >= 3:
        fs.update([w + 'ا', w + 'ای', w + 'ایی', w + 'امون', w + 'اتون', w + 'اشون', w + 'اش', w + 'ام', w + 'ه', w + 'م'])
    if last == 'ی':
        fs.update([w + 'ه'])
    if vowel_end or h_end:
        fs.update([w + 'ست', w + 'یه'])
    return fs

def colloquial_bases(w):
    # Tehran a > u before n/m: خانه > خونه، تمام > تموم، آرام > آروم، آن > اون
    out = set()
    if w.startswith('آن'):
        out.add('اون' + w[2:])
    for m in re.finditer('ا(?=[نم])', w):
        out.add(w[:m.start()] + 'و' + w[m.end():])
        if m.start() > 0 and w[m.start() - 1] == 'و':
            out.add(w[:m.start()] + w[m.end():])   # توانست > تونست
    return out

def verb_forms(inf):
    fs = set()
    if ' ' in inf or not inf.endswith('ن'):
        return fs
    P = inf[:-1]
    pre = ''
    for pv in PREVERBS:
        if inf.startswith(pv) and len(inf) > len(pv) + 3:
            pre = pv
            break
    core_P = P[len(pre):]
    extra_P = set(colloquial_bases(core_P))
    if core_P.startswith('آ'):
        extra_P.add('او' + core_P[1:])
    past_end = ['م', 'ی', '', 'یم', 'ید', 'ند', 'ین', 'ن']
    for cp in extra_P:
        for neg in ['', 'ن']:
            for e in past_end + ['ه']:
                fs.add(pre + neg + cp + e)
                fs.add(pre + neg + 'می' + cp + e)
    for neg in ['', 'ن']:
        for e in past_end:
            fs.add(pre + neg + core_P + e)
            fs.add(pre + neg + 'می' + core_P + e)
        for e in ['ه', 'هام', 'های', 'هایم', 'هاید', 'هاند', 'هاست', 'ه‌ام']:
            fs.add(norm(pre + neg + core_P + e))
    if inf == 'بودن':
        fs.update(['هستم', 'هستی', 'هست', 'هستیم', 'هستید', 'هستند', 'هستین', 'هستن',
                   'نیستم', 'نیستی', 'نیست', 'نیستیم', 'نیستید', 'نیستند', 'نیستین', 'نیستن',
                   'است', 'ست'])
    if inf == 'بایستن':
        fs.update(['باید', 'نباید', 'بایست', 'میبایست', 'نمیبایست'])
        return fs
    all_S = []
    for S0 in present_stems(inf):
        all_S.append(S0)
        all_S.extend(sorted(colloquial_bases(S0)))
    all_S += [S0 + 'ی' for S0 in list(all_S) if S0.endswith('ا') and S0 not in ('خوا', 'آ', 'درآ', 'برآ')]
    for S in dict.fromkeys(all_S):
        core_S = S[len(pre):] if pre and S.startswith(pre) else S
        written = ['م', 'ی', 'د', 'یم', 'ید', 'ند']
        coll = ['م', 'ی', 'د' if core_S.endswith('ا') else 'ه', 'یم', 'ین', 'ن']
        def attach(prefix, stem):
            # ب/ن before a stem beginning with آ or ا: بیا، نیا
            if prefix in ('ب', 'ن') and stem[:1] in ('آ', 'ا'):
                return [prefix + 'ی' + 'ا' + stem[1:]]
            if prefix in ('می', 'نمی') and stem[:1] == 'آ':
                return [prefix + stem, prefix + 'ا' + stem[1:]]
            return [prefix + stem]
        for prefix in ['می', 'نمی', 'ب', 'ن', '']:
            for st in attach(prefix, core_S):
                for e in (written if prefix == '' else written + coll):
                    if prefix == '' and len(st + e) < 3:
                        continue
                    fs.add(pre + st + e)
        # imperative
        for prefix in ['ب', 'ن']:
            for st in attach(prefix, core_S):
                fs.update([pre + st, pre + st + 'ید', pre + st + 'ین'])
        if pre:
            fs.update([pre + core_S, pre + core_S + 'ید', pre + core_S + 'ین'])
        if inf == 'داشتن':
            for e in written + coll:
                fs.add('دار' + e)
                fs.add('ندار' + e)
        if inf == 'خواستن':
            for e in ['م', 'ی', 'د', 'یم', 'ید', 'ند']:
                fs.update(['خواه' + e, 'نخواه' + e])
    fs |= {f + c for f in list(fs) for c in ('ش', 'ت', 'شون', 'تون', 'شو', 'تو') if len(f) > 2}
    return {norm(f) for f in fs if len(norm(f)) > 1}

# form -> list of entry indices
cands = collections.defaultdict(set)
for i, e in enumerate(entries):
    pos = e['pos']
    words = [e['word']] + [v for v in (e.get('variants') or '').split('|') if v.strip()]
    for w in words:
        w = norm(w)
        if not w:
            continue
        if pos == 'VERB':
            if ' ' in w:
                continue
            for f in verb_forms(w):
                cands[f].add(i)
            cands[w].add(i)  # the infinitive itself
        elif pos in NOMINAL:
            if ' ' in w:
                cands[w].add(i)
                continue
            for b in {w} | colloquial_bases(w):
                for f in nominal_forms(b, pos):
                    cands[f].add(i)
        else:
            for b in {w} | colloquial_bases(w):
                cands[b].add(i)
                for c in ['ه', 'م', 'و', 'یه', 'ست', 'ا', 'ها']:
                    if pos in ('PRON', 'DET', 'ADV'):
                        cands[b + c].add(i)

CLITIC_HOSTS = {'به': 'به', 'از': 'از', 'با': 'باها', 'برای': 'برا', 'خود': 'خود', 'واسه': 'واس'}
for i, e in enumerate(entries):
    w = norm(e['word'])
    if w in CLITIC_HOSTS and e['pos'] in ('ADP', 'PRON'):
        h = CLITIC_HOSTS[w]
        hosts = [h, 'به' + 'ه'] if w == 'به' else [h]
        if w == 'به':
            hosts = ['به']
        for hh in hosts:
            for c in ['م', 'ت', 'ش', 'مون', 'تون', 'شون', 'مان', 'تان', 'شان', 'مو', 'تو', 'شو', 'شه', 'ه']:
                cands[hh + c].add(i)
        if w == 'با':
            cands['باهم'].add(i)
        if w == 'برای':
            cands['برا'].add(i)

# hand-made colloquial map: form -> entry id
ids = {e['id']: i for i, e in enumerate(entries)}
colloq = {}
for line in open(COLLOQ, encoding='utf-8'):
    if line.startswith('#') or not line.strip():
        continue
    parts = line.rstrip('\n').split('\t')
    form, target = norm(parts[0]), parts[1].strip()
    colloq[form] = target
    if target in ids:
        cands[form] = {ids[target]}
    elif target == 'IGNORE-SUBS':
        pass
    elif target.startswith('IGNORE') or target.startswith('NEW'):
        cands.pop(form, None)
    else:
        sys.exit(f'unknown target {target} for {form}')

EXACT = 10.0
exact = collections.defaultdict(set)
for i, e in enumerate(entries):
    for w in [e['word']] + [v for v in (e.get('variants') or '').split('|') if v.strip()]:
        exact[norm(w)].add(i)
        if e['pos'] != 'VERB' and len(norm(w)) >= 3:
            for b in colloquial_bases(norm(w)):
                exact[b].add(i)
for form, target in colloq.items():
    if target in ids:
        exact[form] = {ids[target]}

def prior(i, form=None):
    r = int(entries[i]['rank'])
    p = 1.0 / r
    if form is not None and i in exact.get(form, ()):
        p *= EXACT
    return p

def credit(counter):
    out = collections.defaultdict(float)
    unmatched = collections.Counter()
    for form, c in counter.items():
        if len(form) <= 1 and form != 'و':
            continue       # detached suffixes and letters; و is the one one-letter word
        cs = cands.get(form)
        if not cs:
            unmatched[form] += c
            continue
        tot = sum(prior(i, form) for i in cs)
        for i in cs:
            out[i] += c * prior(i, form) / tot
    return out, unmatched

subs = collections.Counter()
for line in open(SUBS, encoding='utf-8'):
    w, c = line.rsplit(' ', 1)
    subs[norm(w)] += int(c)

wf = collections.Counter()
for w in top_n_list('fa', 100000):
    wf[norm(w)] += word_frequency(w, 'fa')

for form, target in colloq.items():
    if target == 'IGNORE-SUBS':
        subs.pop(form, None)   # subtitle credits and release notes, not dialogue
s_out, s_un = credit(subs)
w_out, w_un = credit(wf)

with open(f'{OUT}/entry_counts.tsv', 'w', encoding='utf-8') as f:
    f.write('id\trank\tword\tpos\tsubs\twordfreq\tmultiword\n')
    for i, e in enumerate(entries):
        multi = int(' ' in e['word'])
        f.write(f"{e['id']}\t{e['rank']}\t{e['word']}\t{e['pos']}\t{s_out.get(i, 0):.1f}\t{w_out.get(i, 0):.3e}\t{multi}\n")
new_s = collections.Counter(); new_w = collections.Counter()
for form, target in colloq.items():
    if target.startswith('NEW:'):
        new_s[target] += subs.get(form, 0)
        new_w[target] += wf.get(form, 0)
with open(f'{OUT}/new_counts.tsv', 'w', encoding='utf-8') as f:
    for t, c in new_s.most_common():
        f.write(f'{t}\t{c}\t{new_w[t]:.3e}\n')
with open(f'{OUT}/unmatched.tsv', 'w', encoding='utf-8') as f:
    for form, c in s_un.most_common():
        f.write(f'{form}\t{c}\t{colloq.get(form, "")}\n')
print('subtitle tokens', sum(subs.values()), 'credited', round(sum(s_out.values())), 'unmatched', sum(s_un.values()))
print('wordfreq mass', round(sum(wf.values()), 3), 'credited', round(sum(w_out.values()), 3))
